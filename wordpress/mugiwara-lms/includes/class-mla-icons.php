	/**
	 * Icône en ligne, héritant de la couleur du texte.
	 */
	public static function get( $name, $size = 18, $class = '' ) {
		if ( ! isset( self::PATHS[ $name ] ) ) {
			return '';
		}
		$fill = 'play' === $name ? 'currentColor' : 'none';
		return '<svg class="mla-icon mla-icon--' . esc_attr( $name ) . ( $class ? ' ' . esc_attr( $class ) : '' ) . '" width="' . (int) $size . '" height="' . (int) $size . '" viewBox="0 0 24 24" fill="' . $fill . '" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' . self::PATHS[ $name ] . '</svg>';
	}

	/**
	 * Icône par type de leçon.
	 */
	public static function for_type( $type, $size = 16 ) {
		$map = array(
			'video'    => 'play',
			'audio'    => 'music',
			'pdf'      => 'file-text',
			'document' => 'file',
			'image'    => 'image',
			'folder'   => 'folder',
			'archive'  => 'archive',
			'link'     => 'link',
		);
		return self::get( $map[ $type ] ?? 'play', $size );
	}

	/**
	 * Pièce « Berry » (monnaie du programme de parrainage). Une image personnalisée peut la remplacer dans les réglages.
	 */
	public static function berry( $size = 20 ) {
		$custom = mla_option( 'berry_image' );
		if ( $custom ) {
			return '<img class="mla-berry" src="' . esc_url( $custom ) . '" width="' . (int) $size . '" height="' . (int) $size . '" alt="Berry">';
		}
		return '<svg class="mla-berry" width="' . (int) $size . '" height="' . (int) $size . '" viewBox="0 0 32 32" aria-hidden="true" focusable="false">'
			. '<circle cx="16" cy="16" r="15" fill="#F2B705"/><circle cx="16" cy="16" r="12" fill="#FFD23F" stroke="#C98E00" stroke-width="1.5"/>'
			. '<path d="M12 9.5h5.2a3.4 3.4 0 0 1 1.2 6.6 3.6 3.6 0 0 1-1.1 7H12z M12 16h5.6" fill="none" stroke="#8A5A00" stroke-width="2.2" stroke-linejoin="round"/>'
			. '<path d="M14.5 7.5v17M10 13h2M10 19h2" stroke="#8A5A00" stroke-width="1.6" stroke-linecap="round"/></svg>';
	}
